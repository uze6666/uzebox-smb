#!/usr/bin/env python3
"""gen_text.py -- the game's messages, from your ROM: ../data/textdata.h.

    python gen_text.py            writes ../data/textdata.h

Each message text.c prints is a macro of its tile numbers (the NES font's), read from where the
6502's own screens have it: its VRAM update records in the program (a record is 2 bytes of name
table address, a length, then the tiles), and for the title's two lines the title screen's data
in the CHR-ROM. text.c fills its arrays with them, so no text of the cartridge is in the source.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import asmdata  # noqa: E402

OUT = os.path.join(HERE, "..", "data", "textdata.h")

# macro: [(label, first, count), ...] -- a label of the program, or "CHR" for the CHR-ROM
TEXTS = [
    ("TXT_WORLD",     [("WorldLivesDisplay", 13, 5)]),
    ("TXT_TIMEUP",    [("OnePlayerTimeUp", 3, 7)]),
    ("TXT_GAMEOVER",  [("OnePlayerGameOver", 3, 9)]),
    ("TXT_WARP",      [("WarpZoneWelcome", 3, 21)]),
    ("TXT_THANKS",    [("MarioThanksMessage", 3, 16)]),
    ("TXT_BUTOUR",    [("MushroomRetainerSaved", 3, 22)]),
    ("TXT_ANOTHER",   [("MushroomRetainerSaved", 28, 15)]),
    ("TXT_QUEST",     [("PrincessSaved1", 3, 19)]),
    ("TXT_NEWQUEST",  [("PrincessSaved2", 3, 27)]),
    ("TXT_PUSHB",     [("WorldSelectMessage1", 3, 13)]),
    ("TXT_SELECT",    [("WorldSelectMessage2", 3, 17)]),
    ("TXT_NAMES",     [("MarioThanksMessage", 13, 5), ("LuigiThanksMessage", 13, 5)]),
    ("TXT_THANKSL",   [("LuigiThanksMessage", 3, 16)]),
    ("TXT_PLAYER",    [("CHR", 0x1fb6, 13)]),       # the title screen's data (CHR $1ec0 on)
    ("TXT_TOP",       [("CHR", 0x1fd6, 4)]),
]


def main():
    _, chr_ = asmdata.check_rom()
    L = ["/* textdata.h -- GENERATED by tools/gen_text.py from your ROM; do not edit, never commit.",
         "** The game's messages as NES font tiles, for text.c. */",
         "#pragma once", ""]
    for name, parts in TEXTS:
        b = []
        for lab, first, n in parts:
            src = chr_ if lab == "CHR" else asmdata.bytes_of(lab)
            piece = list(src[first:first + n])
            if len(piece) != n or any(t > 0x2b and t not in (0xaf,) for t in piece):
                sys.exit("gen_text: %s: not a text at %s+%d" % (name, lab, first))
            b += piece
        L.append("#define %s %s" % (name, ", ".join("0x%02x" % v for v in b)))
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print("textdata.h: %d messages" % len(TEXTS))


if __name__ == "__main__":
    main()
