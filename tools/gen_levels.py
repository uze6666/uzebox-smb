#!/usr/bin/env python3
"""gen_levels.py -- the original level data, as C: levels.h, from your ROM (tools/asmdata.py).

    python gen_levels.py            writes ../data/levels.h and prints the sizes

Copies verbatim the area pointer tables (WorldAddrOffsets, AreaAddrOffsets, EnemyAddrHOffsets,
AreaDataHOffsets), the area and enemy data blocks (L_* and E_*, in the asm's order: some areas
are reached by more than one level), and the two address tables as PROGMEM pointer arrays. The
engine's area parser (area.c) and enemy loader read these bytes as the 6502 did.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import asmdata  # noqa: E402  (the cartridge's tables, from your ROM)
OUT = os.path.join(HERE, "..", "data", "levels.h")


def value(tok, labels_rel=None):
    t = tok.strip()
    if t.startswith("$"):
        return int(t[1:], 16)
    if t.startswith("%"):
        return int(t[1:], 2)
    if re.fullmatch(r"\d+", t):
        return int(t)
    raise ValueError(t)


def main():
    data, order = asmdata.parse()

    def bytes_of(label):
        return [value(t) for kind, t in data[label]]

    # the area/enemy blocks, in the asm's order
    area_labels = [l for l in order if re.fullmatch(r"L_(Water|Ground|Underground|Castle)Area\d+", l)]
    enemy_labels = [l for l in order if re.fullmatch(r"E_(Water|Ground|Underground|Castle)Area\d+", l)]
    # the address tables give their order
    def addr_list(lo_label):
        return [t[1:] for kind, t in data[lo_label] if t.startswith("<")]
    area_addr = addr_list("AreaDataAddrLow")
    enemy_addr = addr_list("EnemyDataAddrLow")
    assert set(area_addr) <= set(area_labels) and set(enemy_addr) <= set(enemy_labels)

    # WorldAddrOffsets is label differences: compute them from the AreaAddrOffsets runs
    worlds = ["World%dAreas" % i for i in range(1, 9)]
    area_offsets, world_offsets = [], []
    for w in worlds:
        world_offsets.append(len(area_offsets))
        area_offsets += bytes_of(w)

    L = ["/* levels.h -- the original level data, GENERATED by tools/gen_levels.py from",
         "** your ROM; do not edit, never commit. Read by area.c and the enemy loader as the 6502 read it. */",
         "#pragma once", "",
         "/* LVDATA: where the level blocks are. The flash, unless the build has put them elsewhere",
         "** (SD=1, the .uze: a section of their own, read from the card into SPI RAM: area.c) */",
         "#ifndef LVDATA",
         "#define LVDATA PROGMEM",
         "#endif", ""]
    L.append("const u8 WorldAddrOffsets[8] PROGMEM = {%s};" % ", ".join("0x%02x" % v for v in world_offsets))
    L.append("const u8 AreaAddrOffsets[%d] PROGMEM = {%s};" % (len(area_offsets), ", ".join("0x%02x" % v for v in area_offsets)))
    L.append("static const u8 EnemyAddrHOffsets[4] PROGMEM = {%s};" % ", ".join("0x%02x" % v for v in bytes_of("EnemyAddrHOffsets")))
    L.append("static const u8 AreaDataHOffsets[4] PROGMEM = {%s};" % ", ".join("0x%02x" % v for v in bytes_of("AreaDataHOffsets")))
    L.append("")
    total = 0
    for lab in enemy_labels + area_labels:
        b = bytes_of(lab)
        # an enemy list ends at its $ff. E_GroundArea9 (2-1) has none of its own: the
        # cartridge's is the first byte of the list after it, which a C array does not have
        if lab.startswith("E_") and b[-1] != 0xff:
            b = list(b) + [0xff]
        total += len(b)
        L.append("static const u8 %s[%d] LVDATA = {" % (lab, len(b)))
        for i in range(0, len(b), 16):
            L.append("\t" + ", ".join("0x%02x" % v for v in b[i:i + 16]) + ",")
        L.append("};")
    L.append("")
    def entries(names):
        return ", ".join(names)
    L.append("static const u8 *const EnemyDataAddr[%d] PROGMEM = {%s};" % (len(enemy_addr), entries(enemy_addr)))
    L.append("static const u8 *const AreaDataAddr[%d] PROGMEM = {%s};" % (len(area_addr), entries(area_addr)))
    L.append("")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(L))
    print("levels.h: %d areas, %d enemy blocks, %d bytes of level data (+ %d of tables)"
          % (len(area_labels), len(enemy_labels), total,
             8 + len(area_offsets) + 8 + 2 * (len(area_addr) + len(enemy_addr))))


if __name__ == "__main__":
    sys.exit(main())
