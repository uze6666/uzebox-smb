#!/usr/bin/env python3
"""gen_snd.py -- the sound engine's data, from your ROM (tools/asmdata.py): ../data/snddata.inc, ../data/waves.inc.

    python gen_snd.py            writes both and prints the sizes

snddata.inc: what sound.c (the 6502's SoundEngine) reads, the NES's bytes in the NES's order,
and what apu.c sets the mixer from (sndmodel.py defines both; this only writes them down).
waves.inc: the mixer's waves, the three pulse duties and the triangle.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.dont_write_bytecode = True
import asmdata  # noqa: E402
import sndmodel as M  # noqa: E402


def carray(name, data, note="", used=False, mem="PROGMEM"):
    """used: kept for apu.c's assembly, which the compiler does not see read it. mem: where
    the table is (SNDDATA: the music, which the .uze's build reads from the card)"""
    attr = " __attribute__((used))" if used else ""
    L = [f"static const u8 {name}[{len(data)}] {mem}{attr} = {{" + (f"    /* {note} */" if note else "")]
    for i in range(0, len(data), 16):
        L.append("\t" + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    L.append("};")
    return L


def write_snddata():
    L = ["/* snddata.inc -- generated by tools/gen_snd.py from your ROM: do not edit.",
         " * The 6502 sound engine's tables, each as the ROM has it; the driver reads across the",
         " * ends of some on purpose, so the order inside an array is the ROM's. */", ""]
    L.append("#ifdef SND_APU_TABLES    /* apu.c: the mixer's side (sndmodel.py's definitions) */")
    L.append(f"#define STEP_K {M.STEP_K}         /* pulse step = STEP_K / (period + 1) */")
    L.append(f"#define SNAP_MUL {M.SNAP_MUL}           /* (period + 1) * SNAP_MUL: samples a cycle, 8.8 */")
    L.append(f"#define SOFT_PERIOD {M.SOFT_PERIOD}        /* a pulse's period under it: the triangle's wave */")
    L.append(f"#define TRI_VOL {M.TRI_VOL}           /* the triangle's mixer volume, DMC level 0 */")
    L += carray("PulseVol", M.PULSE_VOL, f"NES volume -> mixer volume, 15 = {M.P15}", True)
    L += carray("NoiseVol", M.NOISE_VOL, "", True)
    L += carray("NoiseParam", M.NOISE_PARAM, "NES noise period -> the mixer's LFSR divider, 15 bits", True)
    L.append("#else                     /* sound.c: the driver's side */")
    L.append("/* SNDDATA: where the music's headers and data are. The flash, unless the build has put them")
    L.append("** elsewhere (SD=1, the .uze: a section of their own, read from the card into SPI RAM) */")
    L.append("#ifndef SNDDATA")
    L.append("#define SNDDATA PROGMEM")
    L.append("#endif")
    total = 0
    tables = [
        ("MusicHeaderData", M.MusicHeaderData,
         "the header offsets (by song, then the ground music's parts), then the headers: "
         "length table offset, data offset (2), triangle, square 1, noise"),
        ("MusicBlob", M.MusicBlob, "Star_CloudMData to VictoryMusData"),
        ("FreqRegLookupTbl", M.FreqRegLookupTbl, "period high, low by note"),
        ("MusicLengthLookupTbl", M.MusicLengthLookupTbl, ""),
        ("EnvData", M.EnvData, "EndOfCastle 4, Area 8, WaterEvent 40, BowserFlame 32, BrickShatter 16"),
        ("SwimStompEnvelopeData", asmdata.bytes_of("SwimStompEnvelopeData"), ""),
        ("ExtraLifeFreqData", asmdata.bytes_of("ExtraLifeFreqData"), ""),
        ("PowerUpGrabFreqData", asmdata.bytes_of("PowerUpGrabFreqData")[:27], ""),
        ("PUp_VGrow_FreqData", asmdata.bytes_of("PUp_VGrow_FreqData"), ""),
        ("BrickShatterFreqData", asmdata.bytes_of("BrickShatterFreqData"), ""),
    ]
    for name, data, note in tables:
        L += carray(name, data, note, mem="SNDDATA" if name in ("MusicHeaderData", "MusicBlob") else "PROGMEM")
        total += len(data)
    for lab in M.ENV_LABELS + ["BrickShatterEnvData"]:
        L.append(f"#define ENV_{lab[:-7] if lab.endswith('EnvData') else lab:22s} {M.EnvAt[lab]}")
    L.append("#endif")
    open(os.path.join(HERE, "..", "data", "snddata.inc"), "w", newline="\n").write("\n".join(L) + "\n")
    return total, tables


def write_waves():
    def page(samples):
        return ["\t.byte " + ",".join(f"0x{s & 0xff:02X}" for s in samples[i:i + 16])
                for i in range(0, 256, 16)]
    L = ["; waves.inc -- generated by tools/gen_snd.py: do not edit.",
         "; Super Uze Brothers' mixer waves (the kernel's MIXER_WAVES), in place of the kernel's 10",
         "; default waves: the NES pulse duties, 0 = square 50%, 1 = square 25% (and 75%),",
         "; 2 = square 12.5%, at the kernel's square levels (0x7f high, 0x80 low); and 3, the",
         "; NES triangle (32 steps of 16 levels), for the APU engine."]
    for i, (name, high) in enumerate((("square 50%", 128), ("square 25%", 64), ("square 12.5%", 32))):
        L.append(f"\t; wave {i}: {name}")
        L += page([0x7f] * high + [0x80] * (256 - high))
    L.append("\t; wave 3: triangle")
    L += page(M.triangle_wave())
    open(os.path.join(HERE, "..", "data", "waves.inc"), "w", newline="\n").write("\n".join(L) + "\n")


def main():
    total, tables = write_snddata()
    write_waves()
    for name, data, _ in tables:
        print(f"  {name:24s} {len(data):5d}")
    print(f"snddata.inc: {total} bytes for the driver, 48 for the mixer's side; waves.inc: 4 waves")


if __name__ == "__main__":
    main()
